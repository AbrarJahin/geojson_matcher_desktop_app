  '        else "MANUAL_REVIEW: 0"\n'
  '    )\n'
  '    print("Manual-review completed:", completed_count)\n'
  '    print("Manual-review remaining:", remaining_count)\n'
  '\n'
  '    if manual_review_count == 0:\n'
  '        return pd.DataFrame()\n'
  '\n'
  '    batch_status_df = (\n'
  '        selected.groupby(\n'
  '            "manual_batch_id",\n'
  '            dropna=False,\n'
  '            as_index=False,\n'
  '        )\n'
  '        .agg(\n'
  '            planned_pairs=(\n'
  '                "pair_key",\n'
  '                "count",\n'
