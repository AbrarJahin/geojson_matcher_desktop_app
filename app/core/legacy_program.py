  'def _replace_nearest_endpoint(\n'
  '    geometry,\n'
  '    nearest_point,\n'
  '    midpoint,\n'
  '):\n'
  '    """\n'
  '    Move the endpoint closest to nearest_point to the shared midpoint.\n'
  '\n'
  '    This preserves the merge procedure used by notebook #6 while also\n'
  '    supporting MultiLineString geometries.\n'
  '    """\n'
  '    def update_line(line):\n'
  '        coordinates = list(\n'
  '            line.coords\n'
  '        )\n'
  '        if len(coordinates) < 2:\n'
  '            raise ValueError(\n'
  '                "A road line contains fewer "\n'
  '                "than two coordinates."\n'
  '            )\n'
  '\n'
  '        start_point = Point(\n'
  '            coordinates[0][:2]\n'
  '        )\n'
  '        end_point = Point(\n'
  '            coordinates[-1][:2]\n'
  '        )\n'
  '\n'
  '        endpoint_index = (\n'
  '            0\n'
  '            if (\n'
  '                start_point.distance(\n'
  '                    nearest_point\n'
  '                )\n'
  '                <= end_point.distance(\n'
  '                    nearest_point\n'
  '                )\n'
  '            )\n'
  '            else -1\n'
  '        )\n'
  '\n'
  '        original = coordinates[\n'
  '            endpoint_index\n'
  '        ]\n'
  '        replacement = (\n'
  '            midpoint.x,\n'
  '            midpoint.y,\n'
  '        )\n'
  '\n'
  '        if len(original) >= 3:\n'
  '            replacement = (\n'
  '                replacement\n'
  '                + tuple(\n'
  '                    original[2:]\n'
  '                )\n'
  '            )\n'
  '\n'
  '        movement_m = Point(\n'
  '            original[:2]\n'
  '        ).distance(\n'
  '            midpoint\n'
  '        )\n'
  '\n'
  '        coordinates[\n'
  '            endpoint_index\n'
  '        ] = replacement\n'
  '\n'
  '        return (\n'
  '            LineString(\n'
  '                coordinates\n'
  '            ),\n'
  '            float(\n'
  '                movement_m\n'
  '            ),\n'
  '        )\n'
  '\n'
  '    if geometry.geom_type == "LineString":\n'
  '        return update_line(\n'
  '            geometry\n'
  '        )\n'
  '\n'
  '    if geometry.geom_type == "MultiLineString":\n'
  '        parts = list(\n'
  '            geometry.geoms\n'
  '        )\n'
  '        if not parts:\n'
  '            raise ValueError(\n'
  '                "An empty MultiLineString "\n'
  '                "cannot be updated."\n'
  '            )\n'
  '\n'
  '        part_index = min(\n'
  '            range(\n'
  '                len(parts)\n'
  '            ),\n'
  '            key=lambda index: parts[\n'
  '                index\n'
  '            ].distance(\n'
  '                nearest_point\n'
  '            ),\n'
  '        )\n'
  '\n'
  '        updated_part, movement_m = (\n'
  '            update_line(\n'
  '                parts[\n'
  '                    part_index\n'
  '                ]\n'
  '            )\n'
  '        )\n'
  '        parts[\n'
  '            part_index\n'
  '        ] = updated_part\n'
  '\n'
  '        return (\n'
  '            MultiLineString(\n'
  '                parts\n'
  '            ),\n'
  '            movement_m,\n'
  '        )\n'
  '\n'
  '    raise ValueError(\n'
  '        "Unsupported geometry type "\n'
  '        f"for connection: "\n'
  '        f"{geometry.geom_type}"\n'
  '    )\n'
  '\n'
  '\n'
  'def _all_endpoints(geometry):\n'
  '    if geometry.geom_type == "LineString":\n'
  '        parts = [geometry]\n'
  '    elif geometry.geom_type == "MultiLineString":\n'
  '        parts = list(\n'
  '            geometry.geoms\n'
  '        )\n'
  '    else:\n'
  '        return []\n'
  '\n'
  '    endpoints = []\n'
  '    for part in parts:\n'
  '        coordinates = list(\n'
  '            part.coords\n'
  '        )\n'
  '        if len(coordinates) >= 2:\n'
  '            endpoints.extend(\n'
  '                [\n'
  '                    Point(\n'
  '                        coordinates[0][:2]\n'
  '                    ),\n'
  '                    Point(\n'
  '                        coordinates[-1][:2]\n'
  '                    ),\n'
  '                ]\n'
  '            )\n'
  '\n'
  '    return endpoints\n'
  '\n'
