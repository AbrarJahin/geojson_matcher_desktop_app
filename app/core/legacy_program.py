def execute_legacy_pipeline(
    namespace: MutableMapping[str, Any],
    stage_callback: Callable[[int, int, str], None] | None = None,
) -> MutableMapping[str, Any]:
    total = len(CELLS)
    for position, (filename, source) in enumerate(CELLS, start=1):
        if stage_callback is not None:
            stage_callback(position, total, filename)
        code = compile(source, filename, "exec")
        exec(code, namespace, namespace)
    return namespace
