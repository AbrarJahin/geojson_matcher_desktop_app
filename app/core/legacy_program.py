  'def _connect_pair_projected(\n'
  '    county_1_road_id,\n'
  '    county_2_road_id,\n'
  '):\n'
  '    """\n'
  '    Core midpoint merge used by both connect_county_roads() and final export.\n'
  '    """\n'
  '    road_1_gdf = _find_single_road(\n'
  '        marion_gdf,\n'
  '        county_1_road_id,\n'
  '        COUNTY_1_NAME,\n'
  '    )\n'
  '    road_2_gdf = _find_single_road(\n'
  '        hamilton_gdf,\n'
  '        county_2_road_id,\n'
  '        COUNTY_2_NAME,\n'
  '    )\n'
  '\n'
  '    geometry_1 = (\n'
  '        road_1_gdf.geometry.iloc[0]\n'
  '    )\n'
  '    geometry_2 = (\n'
  '        road_2_gdf.geometry.iloc[0]\n'
  '    )\n'
  '\n'
  '    nearest_1, nearest_2 = (\n'
  '        nearest_points(\n'
  '            geometry_1,\n'
  '            geometry_2,\n'
  '        )\n'
  '    )\n'
  '\n'
  '    midpoint = Point(\n'
  '        (\n'
  '            nearest_1.x\n'
  '            + nearest_2.x\n'
  '        )\n'
  '        / 2.0,\n'
  '        (\n'
  '            nearest_1.y\n'
  '            + nearest_2.y\n'
  '        )\n'
  '        / 2.0,\n'
  '    )\n'
  '\n'
  '    new_geometry_1, movement_1_m = (\n'
  '        _replace_nearest_endpoint(\n'
  '            geometry_1,\n'
  '            nearest_1,\n'
  '            midpoint,\n'
  '        )\n'
  '    )\n'
  '    new_geometry_2, movement_2_m = (\n'
  '        _replace_nearest_endpoint(\n'
  '            geometry_2,\n'
  '            nearest_2,\n'
  '            midpoint,\n'
  '        )\n'
  '    )\n'
  '\n'
  '    endpoint_gap_after = min(\n'
  '        endpoint_1.distance(\n'
  '            endpoint_2\n'
  '        )\n'
  '        for endpoint_1 in _all_endpoints(\n'
  '            new_geometry_1\n'
  '        )\n'
  '        for endpoint_2 in _all_endpoints(\n'
  '            new_geometry_2\n'
  '        )\n'
  '    )\n'
  '\n'
  '    if endpoint_gap_after > 1e-7:\n'
  '        raise RuntimeError(\n'
  '            "Updated pair "\n'
  '            f"{county_1_road_id}/"\n'
  '            f"{county_2_road_id} "\n'
  '            "does not have a shared "\n'
  '            "endpoint."\n'
  '        )\n'
  '\n'
  '    return {\n'
  '        "road_1_gdf": road_1_gdf,\n'
  '        "road_2_gdf": road_2_gdf,\n'
  '        "new_geometry_1": new_geometry_1,\n'
  '        "new_geometry_2": new_geometry_2,\n'
  '        "nearest_1": nearest_1,\n'
  '        "nearest_2": nearest_2,\n'
  '        "midpoint": midpoint,\n'
  '        "movement_1_m": movement_1_m,\n'
  '        "movement_2_m": movement_2_m,\n'
  '        "endpoint_gap_after_m": float(\n'
  '            endpoint_gap_after\n'
  '        ),\n'
  '    }\n'
  '\n'
  '\n'
  'def connect_county_roads(\n'
  '    county_1_road_id,\n'
  '    county_2_road_id,\n'
  '):\n'
  '    """\n'
  '    Public midpoint-merge function compatible with notebook #6.\n'
  '\n'
  '    It returns two JSON-safe GeoJSON Features. The endpoint nearest to\n'
  '    the other road is moved to the exact shared midpoint.\n'
  '    """\n'
  '    result = _connect_pair_projected(\n'
  '        county_1_road_id,\n'
  '        county_2_road_id,\n'
  '    )\n'
  '\n'
  '    def to_feature(\n'
  '        road_gdf,\n'
  '        projected_geometry,\n'
  '    ):\n'
  '        feature = json.loads(\n'
  '            road_gdf.to_crs(\n'
  '                LATLON_CRS\n'
  '            ).to_json()\n'
  '        )["features"][0]\n'
  '\n'
  '        feature["id"] = (\n'
  '            feature.get(\n'
  '                "properties",\n'
  '                {},\n'
  '            ).get(\n'
  '                ROAD_ID_COL,\n'
  '                feature.get(\n'
  '                    "id"\n'
  '                ),\n'
  '            )\n'
  '        )\n'
  '\n'
  '        latlon_geometry = (\n'
  '            gpd.GeoSeries(\n'
  '                [\n'
  '                    projected_geometry\n'
  '                ],\n'
  '                crs=TARGET_CRS,\n'
  '            )\n'
  '            .to_crs(\n'
  '                LATLON_CRS\n'
  '            )\n'
  '            .iloc[0]\n'
  '        )\n'
  '\n'
  '        feature["geometry"] = mapping(\n'
  '            latlon_geometry\n'
  '        )\n'
  '        return feature\n'
  '\n'
  '    return (\n'
  '        to_feature(\n'
  '            result[\n'
  '                "road_1_gdf"\n'
  '            ],\n'
  '            result[\n'
  '                "new_geometry_1"\n'
  '            ],\n'
  '        ),\n'
  '        to_feature(\n'
  '            result[\n'
  '                "road_2_gdf"\n'
  '            ],\n'
  '            result[\n'
  '                "new_geometry_2"\n'
  '            ],\n'
  '        ),\n'
  '    )\n'
  '\n'
  '\n'
