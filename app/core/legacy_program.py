  'def _resolve_one_to_one_accepted_pairs(decisions):\n'
  '    """\n'
  '    Keep at most one manually accepted pair per road.\n'
  '\n'
  '    Every "yes" row is human-approved in this two-category workflow.\n'
  '    Ties are resolved by higher fused valid-pair probability and then\n'
  '    deterministic pair key.\n'
  '    """\n'
  '    resolved = decisions.copy()\n'
  '    resolved["conflict_rejected"] = False\n'
  '\n'
  '    accepted = resolved.loc[\n'
  '        resolved["final_decision"].eq("yes")\n'
  '    ].copy()\n'
  '\n'
  '    accepted = accepted.sort_values(\n'
  '        [\n'
  '            "probablity",\n'
  '            "model_probability_agreement",\n'
  '            "pair_key",\n'
  '        ],\n'
  '        ascending=[\n'
  '            False,\n'
  '            False,\n'
  '            True,\n'
  '        ],\n'
  '        kind="mergesort",\n'
  '    )\n'
  '\n'
  '    used_county_1 = set()\n'
  '    used_county_2 = set()\n'
  '\n'
  '    for row_index, row in accepted.iterrows():\n'
  '        id_1 = row["county_1_id"]\n'
  '        id_2 = row["county_2_id"]\n'
  '\n'
  '        if (\n'
  '            id_1 in used_county_1\n'
  '            or id_2 in used_county_2\n'
  '        ):\n'
  '            resolved.loc[\n'
  '                row_index,\n'
  '                "final_decision",\n'
  '            ] = "no"\n'
  '            resolved.loc[\n'
  '                row_index,\n'
  '                "conflict_rejected",\n'
  '            ] = True\n'
  '            resolved.loc[\n'
  '                row_index,\n'
  '                "decision_reason",\n'
  '            ] = (\n'
  '                str(\n'
  '                    resolved.loc[\n'
  '                        row_index,\n'
  '                        "decision_reason",\n'
  '                    ]\n'
  '                )\n'
  '                + "|rejected_one_to_one_conflict"\n'
  '            )\n'
  '            continue\n'
  '\n'
  '        used_county_1.add(id_1)\n'
  '        used_county_2.add(id_2)\n'
  '\n'
  '    return resolved\n'
  '\n'
